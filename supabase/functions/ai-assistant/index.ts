import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers":
    "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

const SYSTEM_PROMPT = `You are the AI Assistant for PrepWise — an AI-powered interview preparation and live presentation platform. Your role is to help users navigate and get the most out of the platform.

Key platform features you should know about:
1. **Mock Interviews**: Users can practice interviews by selecting a job title and level. AI generates role-specific questions and provides detailed feedback on answers.
2. **Dashboard**: Shows session history, performance trends, and analytics for past interview sessions.
3. **Live Rooms**: Real-time presentation rooms with PDF slide sharing, WebRTC video/audio calling, screen sharing, chat, and participant lists.
4. **Leaderboard**: Users can see how they rank against peers.
5. **Profile**: Users can update their display name, college, degree, domain, and social links.
6. **Admin Panel**: Admins can manage users, view analytics, and curate question banks.

How to help users:
- Guide them through starting a mock interview (go to /interview, select role and level).
- Explain how to create or join a live room (go to /live, create room, share code).
- Help troubleshoot common issues (camera/mic permissions, PDF upload, joining rooms).
- Give interview tips: STAR method, structuring answers, handling behavioral vs technical questions.
- Suggest how to improve based on their described weaknesses.

Keep answers concise, friendly, and actionable. Use markdown formatting for clarity.`;

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();

    if (!messages || !Array.isArray(messages)) {
      return new Response(
        JSON.stringify({ error: "messages array is required" }),
        { status: 400, headers: { ...corsHeaders, "Content-Type": "application/json" } }
      );
    }

    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) {
      throw new Error("LOVABLE_API_KEY is not configured");
    }

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: SYSTEM_PROMPT },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(
          JSON.stringify({ error: "Rate limit exceeded. Please try again in a moment." }),
          { status: 429, headers: { ...corsHeaders, "Content-Type": "application/json" } }
        );
      }
      if (response.status === 402) {
        return new Response(
          JSON.stringify({ error: "AI credits exhausted. Please add funds." }),
          { status: 402, headers: { ...corsHeaders, "Content-Type": "application/json" } }
        );
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(
        JSON.stringify({ error: "AI service error" }),
        { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } }
      );
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("ai-assistant error:", e);
    return new Response(
      JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }),
      { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } }
    );
  }
});
